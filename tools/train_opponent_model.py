"""
Stage-S2: train the opponent model's starting parameters on recorded arena games.

    python -m arena.run --maps all --games 1 --time 0.15 --save-all-logs        # record games
    python tools/train_opponent_model.py arena/results/traces/<run> [<run2> ...]

1. Style HMM: Baum-Welch (splitter.opponent_model.baum_welch, our own EM) on the observation
   sequences of the TRAIN bots, starting from the hand-set parameters. Held-out bots measure
   generalisation (log-likelihood per turn, trained vs hand-set). Writes splitter/opponent_params.py.
2. Policy HMM: small grid over (stay, eps), scored by the held-out log-likelihood of the
   predicted next steps. Printed (copy the best values into PolicyHMM's defaults if they differ).

Observations are the RECONSTRUCTED features (what the bot will see in a real game).
"""
import glob
import json
import math
import os
import pprint
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from arena.referee import state_from_dict
from splitter.observe import features_from_flows, reconstruct_flows
from splitter.opponent_model import (
    GoalRecognizer,
    PolicyHMM,
    baum_welch,
    default_params,
    phase_of,
    plan_steps,
    sequence_loglik,
)

TRAIN = {"Apex", "Grabber", "Greedy", "RaceMCTS", "Rusher", "Splitter"}
HELD_OUT = {"Expecti", "TacticalSplitter", "Starter"}
OUT = os.path.join(ROOT, "splitter", "opponent_params.py")


def load_games(folders):
    """[(record, {side: [(obs, phase, mid, after, rflows, true_steps)]})] for every game."""
    games = []
    for folder in folders:
        for path in glob.glob(os.path.join(folder, "*.json")):
            with open(path) as f:
                rec = json.load(f)
            per_side = {0: [], 1: []}
            for st in rec["trace"]:
                mover = st["side"]
                mid = state_from_dict(st["before"], rec["rows"], rec["cols"], rec["max_ply"])
                after = state_from_dict(st["after"], rec["rows"], rec["cols"], rec["max_ply"])
                rflows = reconstruct_flows(mid, after, mover)
                obs = features_from_flows(mid, mover, rflows).vector()
                steps = plan_steps([tuple(m) for m in st["moves"]], mid.groups[mover])
                per_side[mover].append((obs, phase_of(mid), mid, after, rflows, steps))
            games.append((rec, per_side))
    return games


def sequences(games, names):
    return [[(o, ph) for o, ph, *_ in turns] for rec, sides in games for s, turns in sides.items()
            if rec["names"][s] in names and turns]


def per_turn(params, seqs):
    n = sum(len(s) for s in seqs)
    return sum(sequence_loglik(params, s) for s in seqs) / max(1, n)


def policy_score(games, names, stay, eps, every=2):
    """Average log-likelihood per enemy-group step of the policy-HMM mixture prediction."""
    total, n = 0.0, 0
    for rec, sides in games:
        for s, turns in sides.items():
            if rec["names"][s] not in names:
                continue
            goals = GoalRecognizer()
            pol = PolicyHMM(goals, stay=stay, eps=eps)
            for i, (_obs, _ph, mid, after, rflows, steps) in enumerate(turns):
                dists = pol.expert_dists(mid, s)
                if i % every == 0:
                    mix = pol.mixture(dists)
                    for pos, cell in steps.items():
                        if pos in mix:
                            total += math.log(max(mix[pos].get(cell, 0.0), 1e-6))
                            n += 1
                goals.update(mid, after, s, rflows)
                pol.update(dists, steps)
    return total / max(1, n)


def main():
    folders = [a for a in sys.argv[1:] if not a.startswith("--")]
    games = load_games(folders)
    tr, ho = sequences(games, TRAIN), sequences(games, HELD_OUT)
    print(f"{len(games)} games: {sum(map(len, tr))} train turns, {sum(map(len, ho))} held-out turns")

    base = default_params()
    params, hist = baum_welch(tr, base, iters=60)
    print(f"Baum-Welch: {len(hist)} iterations, train log-lik {hist[0]:.1f} -> {hist[-1]:.1f}")
    for label, p in (("hand-set", base), ("trained", params)):
        print(f"  {label:9s} log-lik/turn  train {per_turn(p, tr):.4f}   held-out {per_turn(p, ho):.4f}")
    better = per_turn(params, ho) > per_turn(base, ho)
    if better:
        with open(OUT, "w", encoding="utf-8") as f:
            f.write('"""Opponent style-HMM parameters, GENERATED by tools/train_opponent_model.py. Do not edit."""\n')
            f.write("# trained on: " + ", ".join(sorted(TRAIN)) + "; validated on: " + ", ".join(sorted(HELD_OUT)) + "\n")
            f.write("PARAMS = " + pprint.pformat(params, width=110, compact=True) + "\n")
        print(f"  held-out improved: wrote {OUT}")
    else:
        print("  held-out did NOT improve: parameters not written (keeping hand-set defaults)")

    if "--policy-grid" in sys.argv:
        print("policy HMM grid (held-out log-lik per group step, higher is better):")
        best = None
        for stay in (0.9, 0.95, 0.98):
            for eps in (0.05, 0.1, 0.15, 0.25):
                sc = policy_score(games, HELD_OUT, stay, eps)
                print(f"  stay={stay:.2f} eps={eps:.2f}: {sc:.4f}")
                if best is None or sc > best[0]:
                    best = (sc, stay, eps)
        print(f"  best: stay={best[1]} eps={best[2]}")


if __name__ == "__main__":
    main()
